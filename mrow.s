/ Построение спрайта (limb.c spr_draw): n байт точек БК a[] (заливка f — «нет
/ точки») -> пары {маска, цвет} на месте, с конца (a[2i..2i+1] — уже прочитанные
/ a[>= i]). Маска байта — по таблице pmask от a ^ f: 11 у точки, отличной от
/ заливки. Цвет — a & маска. На C (сдвиги, ИЛИ) было ~20 команд на байт.
/ void spr_pairs(uint8_t *a, uint16_t n, uint16_t f)
	.globl	_spr_pairs
_spr_pairs:
	mov	r2, -(sp)
	mov	r3, -(sp)
	mov	r4, -(sp)
	mov	r5, -(sp)
	mov	012(sp), r1
	mov	014(sp), r3
	beq	9f
	add	r3, r1			/ a + n
	mov	r1, r2
	add	r3, r2			/ a + 2n
	mov	016(sp), r4
1:	movb	-(r1), r0
	mov	r0, r5
	xor	r4, r5
	bic	$0177400, r5
	movb	pmask(r5), r5
	com	r5
	bicb	r5, r0			/ a & маска
	com	r5
	movb	r0, -(r2)
	movb	r5, -(r2)
	sob	r3, 1b
9:	mov	(sp)+, r5
	mov	(sp)+, r4
	mov	(sp)+, r3
	mov	(sp)+, r2
	rts	pc

	.data
/ pmask[x]: 2 бита точки — 11, если точка x ненулевая (сравнение в as — -1 или 0)
pmask:
	i = 0
	.rept	0400
	.byte	(((i & 3) != 0) & 3) | (((i & 014) != 0) & 014) | (((i & 060) != 0) & 060) | (((i & 0300) != 0) & 0300)
	i = i + 1
	.endr
