/ Чтение-запись блока диска драйвером ПЗУ КНГМД 326 (`JSR PC, @#160004`) в обход
/ ANDOS (банк C; saveload.c). Код копируется в _bounce и работает оттуда: в
/ раскладке запуска, где видно ПЗУ, нет ни банков, ни общей копии кода — поэтому
/ адреса только абсолютные (@#), переходы — короткие. Рабочая область драйвера —
/ та же, что у ANDOS (0120020): дорожку под головкой драйвер помнит в ней, и
/ после нас ANDOS не промахнётся.
	.globl	_romio_code, _romio_end, _smk_home, _rst
	.text

/ uint16_t romio(uint16_t blk, int16_t words, void *buf): words > 0 — чтение,
/ < 0 — запись (блок 512 байт, длиннее — следующие блоки) -> 0 или код ошибки
_romio_code:
	mov	r2, -(sp)
	mov	r3, -(sp)
	mov	r4, -(sp)
	mov	r5, -(sp)
	mfps	-(sp)
	mtps	$0340
	mov	014(sp), r0		/ блок
	mov	016(sp), r1		/ слов
	mov	020(sp), r2		/ буфер (базовое ОЗУ)
	mov	$0120020, r3		/ рабочая область ANDOS
	mov	@$_smk_home, r4		/ раскладка запуска: ПЗУ 326 в 0160000
	mov	$6, @$0177130
	mov	r4, @$0177130
	mov	$0, @$0177130
	jsr	pc, @$0160004
	mov	$0, r0			/ C не трогает
	bcc	1f
	movb	@$052, r0		/ код ошибки драйвера
	bic	$0177400, r0
	cmp	r0, $7			/ 7: «СТОП» во время операции — игра заново
	bne	2f
	jmp	@$_rst
2:	tst	r0
	bne	1f
	inc	r0
1:	mov	@$03176, r4		/ _cur_page: раскладка вызывающего
	mov	$6, @$0177130
	mov	r4, @$0177130
	mov	$0, @$0177130
	mtps	(sp)+
	mov	(sp)+, r5
	mov	(sp)+, r4
	mov	(sp)+, r3
	mov	(sp)+, r2
	rts	pc
_romio_end:
