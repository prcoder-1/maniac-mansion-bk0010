/ void *memset(void *dst, int c, size_t n)
/
/ ИСПРАВЛЕНО 2026-09-28. Прежняя версия читала аргументы из РЕГИСТРОВ (r1=dst, r0=c, r2=n), а
/ pdp11-aout-gcc передаёт их ЧЕРЕЗ СТЕК и снимает их сам (вызывающий) — проверено по выхлопу
/ `make asm-files`:
/       mov $024,-(sp)      ; n
/       mov $0325,-(sp)     ; c
/       mov $_osc_y,-(sp)   ; dst
/       jsr pc,_memset
/       ...  add $010,sp    ; стек чистит ВЫЗЫВАЮЩИЙ
/ так же читает свои аргументы любая C-функция этого таргета (`_abs16` берёт свой из 02(sp)).
/ Со старой версией ПЕРВЫЙ же вызов memset писал по мусорным адресам и валил машину (PC улетал
/ в ПЗУ, PSW с установленным T-битом). Вызовы memset появляются НЕЯВНО: gcc сам сворачивает в
/ них циклы вида `for (i = 0; i < N; ++i) arr[i] = const;`.
/
/ Смещения с учётом трёх push'ей (SP уменьшился на 6): RA=06(sp), dst=010(sp),
/ c=012(sp), n=014(sp).
/ Все восьмеричные константы с ведущим нулём (иначе GNU as читает их как десятичные).

	.even
	.globl _memset
_memset:
	mov	r2, -(sp)
	mov	r3, -(sp)
	mov	r4, -(sp)

	mov	010(sp), r1			/ dst
	mov	012(sp), r0			/ c — значим только младший байт
	mov	014(sp), r2			/ n
	bic	$0177400, r0			/ старший байт байтового аргумента компилятором не гарантирован
	mov	r1, r4				/ сохранить dst: memset возвращает его в r0

	tst	r2
	beq	ms_done

	bit	$1, r1				/ нечётный адрес — дописать байт и выровняться на слово
	beq	ms_words
	movb	r0, (r1)+
	dec	r2
	beq	ms_done

ms_words:
	mov	r2, r3
	asr	r3				/ r3 = число целых слов
	beq	ms_tail
	mov	r0, -(sp)			/ слово из двух одинаковых байт
	swab	r0
	bis	(sp)+, r0			/ r0 = c | (c << 8), младший байт по-прежнему c
ms_word_loop:
	mov	r0, (r1)+
	sob	r3, ms_word_loop

ms_tail:
	bit	$1, r2				/ нечётный остаток — один байт
	beq	ms_done
	movb	r0, (r1)+

ms_done:
	mov	r4, r0				/ возвращаемое значение — исходный dst
	mov	(sp)+, r4
	mov	(sp)+, r3
	mov	(sp)+, r2
	rts	pc
