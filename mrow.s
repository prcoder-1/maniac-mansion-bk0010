/ Маска глубины на строку готового спрайта (банк C; limb.c spr_draw): пары
/ {точки, цвет} строки — в _band. Байт БК j — точки MM 5j..5j+3 (пятая выпала
/ при сжатии 4:5), от бита bo байта m[0]; бит 7 байта маски — левая точка.
/ Закрытые маской точки снимаются в обоих байтах пары.
	.globl	_spr_mrow
	.text

/ void spr_mrow(uint8_t *pairs, uint16_t w, const uint8_t *m, uint16_t bo, uint16_t ns)
_spr_mrow:
	mov	r2, -(sp)
	mov	r3, -(sp)
	mov	r4, -(sp)
	mov	r5, -(sp)
	mov	016(sp), r3
	mov	022(sp), r5
1:	tstb	(r3)+			/ строка маски пуста — нечего снимать
	bne	2f
	sob	r5, 1b
	br	9f
2:	mov	012(sp), r1
	mov	014(sp), r2
	mov	016(sp), r3
	mov	020(sp), r4
3:	movb	(r3), r0		/ m[k] << 8 | m[k+1]
	swab	r0
	clrb	r0
	bisb	1(r3), r0
	beq	5f
	mov	r4, r5			/ << bo: точки байта — в биты 15..12
	asl	r5
	neg	r5
	jmp	4f(r5)
	asl	r0
	asl	r0
	asl	r0
	asl	r0
	asl	r0
	asl	r0
	asl	r0
4:	swab	r0
	bic	$0177400, r0
	movb	mtab(r0), r0
	bicb	r0, (r1)+
	bicb	r0, (r1)+
	br	6f
5:	tst	(r1)+
6:	add	$5, r4
	cmp	r4, $8
	blt	7f
	sub	$8, r4
	inc	r3
7:	sob	r2, 3b
9:	mov	(sp)+, r5
	mov	(sp)+, r4
	mov	(sp)+, r3
	mov	(sp)+, r2
	rts	pc

