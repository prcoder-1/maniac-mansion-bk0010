/ Проба AZБК (банк D, azboot.c). Регистры платы — 0177000..0177577; на настоящей СМК в
/ режиме All там на чтение — нули её сегмента 3 (smk_twins), запись — в никуда (ловушка).
	.globl	_az_probe
	.text

/ uint16_t az_probe(void): 1 — плата есть: версия ПЛИС (0177370) читается без ловушки, не
/ 0 и не 0177777, страница окна 12 маппера (0177330) хранит записанное. Вектор 4 — на
/ время пробы свой, прерывания закрыты; окно 12 — прежнее (код банка D — ниже 0140000)
_az_probe:
	mfps	-(sp)
	mtps	$0340
	mov	@$4, -(sp)
	mov	@$6, -(sp)
	mov	$7f, @$4
	mov	$0340, @$6
	mov	sp, r1
	mov	@$0177370, r0
	beq	8f
	inc	r0			/ 0177777 -> 0
	beq	8f
	mov	@$0177330, -(sp)
	mov	$012345, @$0177330
	mov	@$0177330, r0
	mov	$05432, @$0177330
	cmp	@$0177330, $05432
	bne	6f
	cmp	r0, $012345
	bne	6f
	mov	(sp)+, @$0177330
	mov	$1, r0
	br	9f
6:	mov	(sp)+, @$0177330
8:	clr	r0
	br	9f
7:	mov	r1, sp			/ ловушка: шины нет
	clr	r0
9:	mov	(sp)+, @$6
	mov	(sp)+, @$4
	mtps	(sp)+
	rts	pc
